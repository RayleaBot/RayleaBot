import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const modes = ['light', 'dark']
const displaySizes = {
  32: { artwork: 'compact', widths: [32, 40, 48, 64, 96] },
  40: { artwork: 'compact', widths: [40, 50, 60, 80, 120] },
  128: { artwork: 'portrait', widths: [128, 160, 192, 256, 384] },
}
const sizes = [...new Set(Object.values(displaySizes).flatMap(value => value.widths))].sort((left, right) => left - right)
const artworkNames = { portrait: 'mark', compact: 'mark-compact' }
const samples = 4
const assetDirectory = 'web/src/assets/brand'
const registryPath = 'web/src/preferences/brand-assets.generated.ts'
const manifestPath = path.join(root, assetDirectory, 'manifest.generated.json')
const arguments_ = process.argv.slice(2)
assert(arguments_.every(argument => ['--check', '--help'].includes(argument)), 'Unknown option')
if (arguments_.includes('--help')) {
  console.log('node scripts/generate-web-brand-assets.mjs [--check]\nRender Web brand images from pure SVG with the existing Launcher @napi-rs/canvas dependency. --check needs only Node.js.')
  process.exit(0)
}

const readText = file => fs.readFileSync(path.join(root, file), 'utf8').replaceAll('\r\n', '\n')
const sha256 = value => createHash('sha256').update(value).digest('hex')
const sources = Object.fromEntries(Object.entries(artworkNames).map(([artwork, name]) => [artwork,
  Object.fromEntries(modes.map(mode => [mode, readText(`design/${name}-${mode}.svg`)])),
]))
for (const themes of Object.values(sources)) for (const svg of Object.values(themes)) assert.doesNotMatch(svg, /<image\b|<foreignObject\b|(?:href|url\(|data:|base64)/i)
const canvasVersion = JSON.parse(readText('launcher/package.json')).devDependencies['@napi-rs/canvas']
const inputs = {
  svg: Object.fromEntries(Object.entries(artworkNames).map(([artwork, name]) => [artwork,
    Object.fromEntries(modes.map(mode => [mode, { path: `design/${name}-${mode}.svg`, sha256: sha256(sources[artwork][mode]) }])),
  ])),
  generator: { path: 'scripts/generate-web-brand-assets.mjs', sha256: sha256(readText('scripts/generate-web-brand-assets.mjs')) },
  rasterizer: { module: '@napi-rs/canvas', version: canvasVersion },
  samples,
  displaySizes,
}
const filename = (artwork, mode, size) => `${artworkNames[artwork]}-${mode}-${size}.png`
const identifier = (artwork, mode, size) => `${artwork}${mode}${size}`
const images = [...new Map(modes.flatMap(mode => Object.values(displaySizes).flatMap(({ artwork, widths }) => widths.map(size => {
  const file = `${assetDirectory}/${filename(artwork, mode, size)}`
  return [file, { artwork, mode, size, file }]
})))).values()]

function registry() {
  return '// Generated by scripts/generate-web-brand-assets.mjs from portrait and compact SVG masters. Do not edit.\n\n'
    + images.map(({ artwork, mode, size }) => `import ${identifier(artwork, mode, size)} from '../assets/brand/${filename(artwork, mode, size)}?no-inline'`).join('\n')
    + '\n\nexport const rayleaMarkSources = {\n'
    + modes.map(mode => `  ${mode}: {\n${Object.entries(displaySizes).map(([displaySize, { artwork, widths }]) => `    ${displaySize}: {\n      artwork: '${artwork}',\n      src: ${identifier(artwork, mode, displaySize)},\n      srcset: [${widths.map(size => `\`${'${'}${identifier(artwork, mode, size)}} ${size}w\``).join(', ')}].join(', '),\n    },`).join('\n')}\n  },`).join('\n')
    + '\n} as const\n'
}

async function renderPng(canvasModule, svg, size) {
  const { createCanvas, loadImage } = canvasModule
  const sourceSize = size * samples
  const source = await loadImage(Buffer.from(svg.replace('<svg ', `<svg width="${sourceSize}" height="${sourceSize}" `)))
  const canvas = createCanvas(sourceSize, sourceSize)
  const context = canvas.getContext('2d')
  context.drawImage(source, 0, 0)
  const input = context.getImageData(0, 0, sourceSize, sourceSize).data
  const result = createCanvas(size, size)
  const target = result.getContext('2d')
  const pixels = target.createImageData(size, size)
  // 按预乘 alpha 累积采样，避免透明边缘在缩小时混入黑边。
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    let alpha = 0
    const color = [0, 0, 0]
    for (let dy = 0; dy < samples; dy++) for (let dx = 0; dx < samples; dx++) {
      const index = ((y * samples + dy) * sourceSize + x * samples + dx) * 4
      const a = input[index + 3]
      alpha += a
      for (let channel = 0; channel < 3; channel++) color[channel] += input[index + channel] * a
    }
    const index = (y * size + x) * 4
    for (let channel = 0; channel < 3; channel++) pixels.data[index + channel] = alpha ? Math.round(color[channel] / alpha) : 0
    pixels.data[index + 3] = Math.round(alpha / (samples * samples))
  }
  target.putImageData(pixels, 0, 0)
  return result.toBuffer('image/png')
}

function fingerprints() {
  return Object.fromEntries([
    ...images.map(({ file }) => [file, sha256(fs.readFileSync(path.join(root, file)))]),
    [registryPath, sha256(readText(registryPath))],
  ])
}

if (!arguments_.includes('--check')) {
  const launcherRequire = createRequire(path.join(root, 'launcher/package.json'))
  assert.equal(launcherRequire('@napi-rs/canvas/package.json').version, canvasVersion)
  const canvasModule = launcherRequire('@napi-rs/canvas')
  fs.mkdirSync(path.join(root, assetDirectory), { recursive: true })
  for (const { artwork, mode, size, file } of images) fs.writeFileSync(path.join(root, file), await renderPng(canvasModule, sources[artwork][mode], size))
  fs.writeFileSync(path.join(root, registryPath), registry())
  fs.writeFileSync(manifestPath, JSON.stringify({ inputs, sizes, files: fingerprints() }, null, 2) + '\n')
}

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
const regenerationHint = 'Run node scripts/generate-web-brand-assets.mjs'
assert.deepEqual(manifest.inputs, inputs, `Web brand inputs changed. ${regenerationHint}`)
assert.deepEqual(manifest.sizes, sizes, regenerationHint)
assert.equal(readText(registryPath), registry(), regenerationHint)
for (const { size, file } of images) {
  const png = fs.readFileSync(path.join(root, file))
  assert(png.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])), `${file} is not PNG`)
  assert.equal(png.readUInt32BE(16), size, `${file} width`)
  assert.equal(png.readUInt32BE(20), size, `${file} height`)
  assert.equal(png[25], 6, `${file} must preserve RGBA transparency`)
}
assert.deepEqual(manifest.files, fingerprints(), `Web brand assets are stale. ${regenerationHint}`)
console.log(`Web brand assets are current: ${modes.length} themes, ${sizes.length} sizes, ${samples}× supersampling.`)
