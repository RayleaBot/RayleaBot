def at(document, pointer):
    for part in pointer.strip("/").split("/") if pointer else []:
        part = part.replace("~1", "/").replace("~0", "~")
        document = document[int(part)] if isinstance(document, list) else document[part]
    return document


def shape(node, root):
    if not isinstance(node, dict):
        return {}
    if "$ref" in node:
        if not node["$ref"].startswith("#/"):
            raise ValueError("wire generator accepts only local schema references")
        node = {**at(root, node["$ref"][1:]), **{key: value for key, value in node.items() if key != "$ref"}}
    result = {key: value for key, value in node.items() if key not in {"allOf", "oneOf", "anyOf"}}
    for part in node.get("allOf", []):
        part = shape(part, root)
        if "properties" in part:
            result["properties"] = {**result.get("properties", {}), **part["properties"]}
        if "required" in part:
            result["required"] = sorted(set(result.get("required", [])) | set(part["required"]))
        if "type" in part:
            result["type"] = part["type"]
        elif kind(part) != "any" and "type" not in result:
            result["type"] = kind(part)
    alternatives = node.get("oneOf", node.get("anyOf", []))
    if alternatives:
        alternatives = [shape(part, root) for part in alternatives]
        object_alternatives = [part for part in alternatives if "properties" in part or part.get("type") == "object"]
        if len(object_alternatives) == len(alternatives):
            fields = {}
            for part in alternatives:
                for key, value in part.get("properties", {}).items():
                    if key in fields and fields[key] != value:
                        fields[key] = {"anyOf": [fields[key], value]}
                    else:
                        fields[key] = value
            base_fields = result.get("properties", {})
            fields = {**base_fields, **{
                key: {"allOf": [base_fields[key], value]} if key in base_fields else value
                for key, value in fields.items()
            }}
            required = set(result.get("required", [])) | set.intersection(*(set(part.get("required", [])) for part in alternatives))
            result.update(type="object", properties=fields, required=sorted(required))
        else:
            kinds = {kind(part) for part in alternatives} - {"null"}
            if len(kinds) == 1:
                result["type"] = kinds.pop()
    return result


def kind(node):
    value = node.get("type")
    if isinstance(value, list):
        nonnull = [item for item in value if item != "null"]
        return nonnull[0] if len(nonnull) == 1 else "any"
    if value:
        return value
    if "properties" in node:
        return "object"
    if node.get("enum") and all(isinstance(value, str) for value in node["enum"]):
        return "string"
    if "const" in node:
        value = node["const"]
        return "boolean" if isinstance(value, bool) else "integer" if isinstance(value, int) else "string"
    return "any"


def go_name(name):
    special = {"id": "ID", "ids": "IDs", "url": "URL", "urls": "URLs", "http": "HTTP", "kv": "KV", "qq": "QQ", "openid": "OpenID", "onebot": "OneBot"}
    return "".join(special.get(part, part.title()) for part in name.split("_"))


class GoModels:
    def __init__(self, schema):
        self.schema = schema
        self.named_nodes = {id(at(schema, path)): name for name, path in MODELS.items()}

    def field_type(self, model, name, node, required):
        if model == "ProtocolEventFrame" and name == "raw_payload":
            return "any"
        if (model, name) in RAW_FIELDS:
            return "json.RawMessage"
        if model == "ProtocolActionConfigWriteFrame" and name == "values":
            return "map[string]json.RawMessage"
        if name == "scope" and model.startswith("ProtocolActionGovernance"):
            return "GovernanceScope"
        if model in {"ProtocolMessageFrame", "ProtocolOutboundMessageFrame"} and name == "segments":
            return "[]ProtocolSegmentFrame"
        resolved = at(self.schema, node["$ref"][1:]) if isinstance(node, dict) and "$ref" in node else node
        named = self.named_nodes.get(id(resolved))
        expanded = shape(node, self.schema)
        category = kind(expanded)
        if named and named != model and category == "object":
            result = named if required else "*" + named
        elif category == "string":
            result = "string"
        elif category == "integer":
            result = "int64" if name in {"timestamp", "time", "received_at", "client_timestamp"} else "int"
        elif category == "number":
            result = "float64"
        elif category == "boolean":
            result = "bool"
        elif category == "array":
            result = "[]" + self.field_type(model, name + "_item", expanded.get("items", {}), True)
        elif category == "object":
            additional = expanded.get("additionalProperties")
            value_type = self.field_type(model, name + "_value", additional, True) if isinstance(additional, dict) else "any"
            result = "map[string]" + value_type
        else:
            result = "any"
        if (model, name) in PRESENCE_FIELDS and not result.startswith("*"):
            result = "*" + result
        return result

    def render(self):
        lines = [HEADER, "package pluginwire\n", 'import "encoding/json"\n']
        shapes = {}
        for name, pointer in MODELS.items():
            node = shape(at(self.schema, pointer), self.schema)
            fields = node.get("properties", {})
            if not fields:
                raise ValueError(f"{pointer}: expected a named object projection")
            shapes[name] = node
            lines.append(f"type {name} struct {{")
            for field, property_schema in fields.items():
                required = field in node.get("required", [])
                go_type = self.field_type(name, field, property_schema, required)
                optional = "" if required else ",omitempty"
                lines.append(f' {go_name(field)} {go_type} `json:"{field}{optional}"`')
            lines.append("}\n")
        # A decoding/dispatch projection combines the top-level alternatives. Its
        # raw event/data fields retain unions; Validate checks the selected branch.
        variants = ["InitFrame", "InitProgressFrame", "InitAckFrame", "EventFrame", "ActionFrame", "ResultFrame", "ErrorFrame", "PingFrame", "PongFrame", "ShutdownFrame"]
        fields = {}
        required_by_type = {}
        for variant in variants:
            node = shapes[variant]
            discriminator = shape(node["properties"]["type"], self.schema).get("const", "action")
            required_by_type[discriminator] = node.get("required", [])
            for name, property_schema in node["properties"].items():
                fields.setdefault(name, (variant, property_schema))
        lines.append("type Frame struct {")
        for name, (variant, property_schema) in fields.items():
            go_type = "json.RawMessage" if name in {"event", "data"} else self.field_type(variant, name, property_schema, True)
            if name == "bots":
                go_type = "*[]BotIdentity"
            suffix = "" if name in {"type", "request_id"} else ",omitempty"
            lines.append(f' {go_name(name)} {go_type} `json:"{name}{suffix}"`')
        lines.append("}\n")
        lines += ["func (frame Frame) MarshalJSON() ([]byte, error) {", " type plain Frame", " encoded, err := json.Marshal(plain(frame)); if err != nil { return nil, err }", " var object map[string]json.RawMessage; if err := json.Unmarshal(encoded, &object); err != nil { return nil, err }", " switch frame.Type {"]
        for discriminator, required in required_by_type.items():
            lines.append(f" case {json.dumps(discriminator)}:")
            for field in required:
                lines.append(f'  if _, present := object[{json.dumps(field)}]; !present {{ value, err := json.Marshal(frame.{go_name(field)}); if err != nil {{ return nil, err }}; object[{json.dumps(field)}] = value }}')
        lines += [" }", " return json.Marshal(object)", "}\n"]
        return "\n".join(lines)


