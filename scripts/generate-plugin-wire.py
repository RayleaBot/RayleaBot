def sync_owned_data(outputs, verify):
    # Raw schema copies and JSON test vectors cannot carry Go ownership headers.
    # These generated-data directories are exclusively owned by this generator.
    stale = []
    for directory in [
        "server/internal/plugins/pluginwire", "sdk/go/internal/pluginwire",
        "server/internal/plugins/pluginwire/testdata", "sdk/go/internal/pluginwire/testdata",
        "server/internal/platform/redact/testdata", "sdk/go/testdata",
    ]:
        for pattern in ("*.schema.json", "*.generated.json"):
            for path in (ROOT / directory).glob(pattern):
                if path not in outputs:
                    if verify:
                        stale.append(path.relative_to(ROOT).as_posix())
                    else:
                        path.unlink()
    return sorted(stale)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args()
    outputs = generate()
    failures = sync_outputs(ROOT, outputs, b"Code generated by scripts/generate-plugin-wire.py", args.verify)
    failures.extend(sync_owned_data(outputs, args.verify))
    if failures:
        raise SystemExit("plugin wire generation drift: " + ", ".join(failures))
    print("plugin wire verified" if args.verify else "plugin wire generated")


if __name__ == "__main__":
    main()
